/* ==========================================
   QUEUE FUNCTIONS
========================================== */

function addToQueue(songIndex) {

    playQueue.push(songIndex);

    showToast("Added to Queue");

    renderQueue();
}

function playNext(songIndex) {

    playQueue.unshift(songIndex);

    showToast("Will play next");

    renderQueue();
}

function removeFromQueue(index) {

    playQueue.splice(index, 1);

    renderQueue();
}

function renderQueue() {

    queueList.innerHTML = "";

    if (playQueue.length === 0) {

        queueList.innerHTML = `
            <p class="empty-queue">
                Queue is empty
            </p>
        `;

        return;
    }

    playQueue.forEach((songIndex, index) => {

        const song = songs[songIndex];

        const item = document.createElement("div");

        item.className = "song-card";

        item.innerHTML = `
            <div class="song-info">
                <img src="${song.image}">
                <div class="song-text">
                    <h3>${song.title}</h3>
                    <p>${song.artist}</p>
                </div>
            </div>

            <button class="remove-btn">
                <i class="fa-solid fa-trash"></i>
            </button>
        `;

        item.querySelector(".remove-btn").addEventListener("click", (e) => {

            e.stopPropagation();

            removeFromQueue(index);

        });

        queueList.appendChild(item);

    });

}


