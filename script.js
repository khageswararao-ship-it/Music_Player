function nextSong() {

    // Play queued songs first
    if (playQueue.length > 0) {

        currentSong = playQueue.shift();

        loadSong(currentSong);
        playSong();

        renderQueue();

        return;
    }

    if (shuffleMode) {

        currentSong = Math.floor(Math.random() * songs.length);

    } else {

        currentSong++;

        if (currentSong >= songs.length) {
            currentSong = 0;
        }

    }

        loadSong(currentSong);
        playSong();
        displaySongs();

}

