function loadSong(index){

    const song = songs[index];

        // Add song to Recently Played
    recentSongs = recentSongs.filter(s => s.title !== song.title);
    recentSongs.unshift(song);

    if (recentSongs.length > 20) {
        recentSongs.pop();
    }

    audio.src = song.audio;

    albumImage.src = song.image;
    miniImage.src = song.image;

    songTitle.textContent = song.title;
    miniTitle.textContent = song.title;

    songArtist.textContent = song.artist;
    miniArtist.textContent = song.artist;

    songAlbum.textContent = song.album;
}


function changePage(callback){

    songList.classList.add("page-change");

    setTimeout(() => {

        callback();

        songList.classList.remove("page-change");

    }, 180);

}


