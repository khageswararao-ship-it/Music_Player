function savePlaylists() {
    localStorage.setItem("playlists", JSON.stringify(playlists));
}

function createPlaylist() {
    const name = prompt("New playlist name:");
    if (!name) return;

    playlists.push({
        name: name,
        songs: []
    });

    savePlaylists();

    // Only refresh if the Playlist page is currently open
    if (playlistBtn.classList.contains("active")) {
        displayPlaylists();
    }
}

function renamePlaylist(index) {
    const name = prompt("New playlist name:", playlists[index].name);
    if (!name) return;

    playlists[index].name = name;

    savePlaylists();
    displayPlaylists();
}

function deletePlaylist(index){

    playlistToDelete = index;

    confirmModal.classList.add("active");

}

function addSongToPlaylist(songIndex, playlistIndex) {
    if (!playlists[playlistIndex].songs.includes(songIndex)) {
        playlists[playlistIndex].songs.push(songIndex);
        savePlaylists();
    }
}

function showPlaylistMenu(songIndex){

    if(playlists.length===0){
        showToast("Create a playlist first");
        return;
    }

    playlistList.innerHTML="";

    playlists.forEach((playlist,index)=>{

        const item=document.createElement("div");

        item.className="popup-playlist";

        item.textContent=playlist.name;

        item.addEventListener("click",()=>{

            addSongToPlaylist(songIndex,index);

            playlistPopup.classList.remove("active");

            showToast("Added to " + playlist.name);

        });

        playlistList.appendChild(item);

    });

    playlistPopup.classList.add("active");
}

function removeSongFromPlaylist(songIndex, playlistIndex) {

    playlists[playlistIndex].songs =
        playlists[playlistIndex].songs.filter(i => i !== songIndex);

    savePlaylists();

    showToast("Song removed from playlist");
}


function setActiveMenu(activeBtn) {

    document.querySelectorAll(".menu li").forEach(item => {
        item.classList.remove("active");
    });

    activeBtn.classList.add("active");

}

